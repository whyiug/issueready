const definitions =
  onlyOutput === null
    ? allDefinitions
    : allDefinitions.filter((definition) => definition.output === onlyOutput);
if (definitions.length === 0) {
  throw new TypeError(`Unknown generated output: ${onlyOutput}`);
}

const bannerComment = `/*
 * Generated from schemas/v1alpha1 by scripts/generate-schema-types.mjs.
 * Do not edit this file directly; edit the JSON Schema and regenerate.
 */`;
const localSchemaReferences = new Map([
  [
    "https://example.invalid/issueready/normalization/v1alpha1",
    join(repositoryRoot, "schemas/v1alpha1/normalization.schema.json"),
  ],
  [
    "https://example.invalid/issueready/snapshot/v1alpha1",
    join(repositoryRoot, "schemas/v1alpha1/snapshot.schema.json"),
  ],
]);

async function generate(definition) {
  const schemaPath = join(repositoryRoot, definition.schema);
  const source = JSON.parse(await readFile(schemaPath, "utf8"));
  const schemaForTypes = { ...source, title: definition.rootName };
  const generated = await compile(schemaForTypes, definition.rootName, {
    bannerComment,
    cwd: dirname(schemaPath),
    $refOptions: {
      resolve: {
        http: false,
        issuereadyLocal: {
          order: 1,
          canRead: (file) =>
            localSchemaReferences.has(file.url.split("#", 1)[0]),
          read: async (file) => {
            const path = localSchemaReferences.get(file.url.split("#", 1)[0]);
            if (path === undefined) {
              throw new TypeError(`Unregistered schema reference: ${file.url}`);
            }
            return readFile(path, "utf8");
          },
        },
      },
    },
    declareExternallyReferenced: true,
    enableConstEnums: false,
    format: true,
    ignoreMinAndMaxItems: false,
    style: {
      bracketSpacing: true,
      printWidth: 80,
      semi: true,
      singleQuote: false,
      tabWidth: 2,
      trailingComma: "all",
      useTabs: false,
    },
    unreachableDefinitions: true,
    unknownAny: false,
  });
  return generated.replaceAll("\r\n", "\n");
}

const failures = [];
if (!checkOnly) await mkdir(outputDirectory, { recursive: true });

for (const definition of definitions) {
  const outputPath = join(outputDirectory, definition.output);
  const generated = await generate(definition);
  if (checkOnly) {
    let current = null;
    try {
      current = await readFile(outputPath, "utf8");
    } catch {
      // A missing generated file is reported as drift below.
    }
    if (current !== generated) failures.push(definition.output);
  } else {
    await writeFile(outputPath, generated, "utf8");
    console.log(`generated ${relative(repositoryRoot, outputPath)}`);
  }
}

if (checkOnly && onlyOutput === null) {
  let existing = [];
  try {
    existing = (await readdir(outputDirectory)).filter((name) =>
      name.endsWith(".ts"),
    );
  } catch {
    // The missing directory is already represented by every expected file.
  }
  const expected = new Set(definitions.map((definition) => definition.output));
  const stale = existing.filter((name) => !expected.has(name));
  failures.push(...stale.map((name) => `stale:${name}`));
}

if (failures.length > 0) {
  console.error(
    `Generated schema types are out of date: ${failures.sort().join(", ")}`,
  );
  console.error("Run: corepack pnpm generate:schema-types");
  process.exitCode = 1;
} else if (checkOnly) {
  console.log(
    `Generated schema types are current (${definitions.length} files).`,
  );
}
